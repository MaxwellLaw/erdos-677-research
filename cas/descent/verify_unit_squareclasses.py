#!/usr/bin/env python3
"""Exact nonsquare witnesses; Dirichlet's theorem supplies completeness."""
from fractions import Fraction as Q
from certificate_io import finish
import hashlib
import json
from pathlib import Path
from verify_export_algebra import norm, prime

ROOT=Path(__file__).resolve().parent
WITNESSES=[(5,2,2),(29,7,10),(13,9,7),(13,8,7)]

def main():
    if not __debug__:raise RuntimeError('Run without optimization')
    source=ROOT/'export_algebra_checks.json';data=json.loads(source.read_text());rows=[]
    for row,(p,r,value) in zip(data['curves'],WITNESSES,strict=True):
        abc=row['a2_a4_a6'];u=tuple(map(Q,row['exported_units'][1]));a2,a4,a6=abc
        assert int(row['order_discriminant'])<0 and norm(u,abc) in (-1,1)
        assert prime(p) and p%4==1 and int(row['order_discriminant'])%p
        assert all(c.denominator%p for c in u)
        assert (r**3+a2*r*r+a4*r+a6)%p==0
        assert (3*r*r+2*a2*r+a4)%p
        assert all(Q(c).denominator%p for v in row['order_basis'] for c in v)
        actual=sum(c.numerator*pow(c.denominator,-1,p)*pow(r,i,p) for i,c in enumerate(u))%p
        assert actual==value and pow(value,(p-1)//2,p)==p-1
        assert pow(p-1,(p-1)//2,p)==1
        rows.append({'case':row['case'],'prime':p,'root_of_f':r,'unit_image':value,'unit_legendre_symbol':-1,'minus_one_legendre_symbol':1,'unit_coefficients':row['exported_units'][1]})
    out={'status':'exact residue witnesses; full unit squareclass conclusion also uses verified maximal orders and Dirichlet unit theorem for signature (1,1), not Lean verified','conclusion':'In each cubic field O_K^*/(O_K^*)^2 is generated by the classes of -1 and the displayed unit','algebra_checks_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'curves':rows}
    target=ROOT/'unit_squareclass_checks.json';digest=finish(target,out)
    print('PASS: all four units are neither a square nor the negative of a square')
    print('output_sha256',digest)
if __name__=='__main__':main()
