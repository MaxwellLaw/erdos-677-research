#!/usr/bin/env python3
"""Export the recorded Bernstein witnesses as kernel-replayable Lean proofs.

Default mode checks byte equality; --write regenerates the new source file.
The JSON is discovery data. Every sign, identity, cover and global inequality
is proved by Lean; this exporter is not part of the trusted kernel.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "cas/saturation/small_height_certificate.json"
TARGET = ROOT / "LcmSix/DuplicationCertificates.lean"


def lit(value):
    return f"({value})"


def render():
    data = json.loads(SOURCE.read_text())
    out = ['''/-
Copyright (c) 2026 MaxwellLaw. Released under the Apache 2.0 license.
-/
import LcmSix.DuplicationBounds

/-!
All rational Bernstein leaves used in the global real duplication bound.
Generated by scripts/export_duplication_certificates.py from the exact
witnesses in cas/saturation/small_height_certificate.json. The generator is
untrusted: Lean proves every identity, positivity condition, interval cover,
and homogeneous conclusion using kernel-replayed tactics.
-/

namespace LcmSix.DuplicationBounds
''']
    for curve in data['curves']:
        a,b,c=map(str,curve['a2_a4_a6'])
        ns='Branch'+'_'.join(map(str,curve['pair']))
        out.append(f'\nnamespace {ns}\n')
        for chart,coordinate in [('finite_chart',False),('reciprocal_chart',True)]:
            name = 'reciprocal' if coordinate else 'finite'
            leaves=curve['archimedean_bernstein_cover'][chart]
            for i,leaf in enumerate(leaves):
                L,U=map(lit,[leaf['left'],leaf['right']])
                cs=list(map(lit,leaf['bernstein_coefficients']))
                s=leaf['sign']
                pol=leaf['polynomial']
                args=f'{lit(a)} {lit(b)} {lit(c)} '+('1 x' if coordinate else 'x 1')
                fx=f'{pol} {args}'
                signed=fx if s==1 else f'-({fx})'
                coeff_args=' '.join(f'(c{j} := {v})' for j,v in enumerate(cs))
                abslemma='le_abs_self' if s==1 else 'neg_le_abs'
                maxlemma='le_max_left' if pol=='F' else 'le_max_right'
                out.append(f'''private theorem {name}_{i} {{x : ℝ}}
    (hL : {L} ≤ x) (hU : x ≤ {U}) :
    1 ≤ 32*pairNorm {args} := by
  have h := lower_bound_of_bernstein
    (f := fun x => {signed}) (L := {L}) (U := {U})
    {coeff_args}
    (by norm_num) (by norm_num) (by norm_num) (by norm_num)
    (by norm_num) (by norm_num)
    (by intro t; unfold {pol} bernstein4; ring) hL hU
  have habs : {signed} ≤ pairNorm {args} :=
    ({abslemma} _).trans ({maxlemma} _ _)
  linarith only [h, habs]
''')
            args=f'{lit(a)} {lit(b)} {lit(c)} '+('1 x' if coordinate else 'x 1')
            out.append(f'''/-- Exact real interval coverage of the {name} chart. -/
theorem {name}_chart (x : ℝ) (hx : |x| ≤ 1) :
    1 ≤ 32*pairNorm {args} := by
  obtain ⟨hl, hu⟩ := abs_le.mp hx
''')
            if len(leaves)==1:
                out.append(f'  exact {name}_0 hl hu\n')
            else:
                for i,leaf in enumerate(leaves[:-1]):
                    out.append(f'  rcases le_total x {lit(leaf["right"])} with h{i} | h{i}\n')
                    prev='hl' if i==0 else f'h{i-1}'
                    out.append(f'  · exact {name}_{i} {prev} h{i}\n')
                out.append(f'  exact {name}_{len(leaves)-1} h{len(leaves)-2} hu\n')
        out.append(f'''/-- The global real lower bound, including the projective chart at infinity. -/
theorem global_lower (p q : ℝ) :
    max |p| |q| ^ 4 ≤ 32*max |F {lit(a)} {lit(b)} {lit(c)} p q|
      |G {lit(a)} {lit(b)} {lit(c)} p q| :=
  global_bound_of_charts finite_chart reciprocal_chart p q

/-- The same bound for the exact integer polynomials used by the gcd layer. -/
theorem integer_lower (p q : ℤ) :
    max |p| |q| ^ 4 ≤ 32*max |HeightCertificates.F {lit(a)} {lit(b)} {lit(c)} p q|
      |HeightCertificates.G {lit(a)} {lit(b)} {lit(c)} p q| := by
  have h := global_lower (p : ℝ) (q : ℝ)
  have hf := F_cast {lit(a)} {lit(b)} {lit(c)} p q
  have hg := G_cast {lit(a)} {lit(b)} {lit(c)} p q
  norm_num only [Int.cast_neg, Int.cast_ofNat] at hf hg
  rw [hf, hg] at h
  exact_mod_cast h

end {ns}
''')
    out.append('\nend LcmSix.DuplicationBounds\n')
    return '\n'.join(out)


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--write',action='store_true')
    args=p.parse_args()
    expected=render()
    if args.write:
        TARGET.write_text(expected)
    else:
        if TARGET.read_text()!=expected:
            raise SystemExit('FAIL: generated duplication certificate source differs')
    print('PASS: 34 exact Bernstein leaves, eight chart bounds and four global real/integer bounds')

if __name__=='__main__':
    main()
