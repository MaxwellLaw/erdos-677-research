#!/usr/bin/env python3
"""Export explicit rational logarithm witnesses. Lean verifies every inequality.
No analytic assertion from this generator is trusted by Lean.
"""
from pathlib import Path
from fractions import Fraction as Q
import json,sys,argparse,hashlib
ROOT=Path(__file__).resolve().parents[1]
TERMS=40
PREC=80

def rat(q):
    q=Q(q)
    return f'({q.numerator}/{q.denominator})' if q.denominator!=1 else str(q.numerator)

def bounds(s):
    z=(s-1)/(s+1)
    lower=2*sum((z**(2*i+1)/Q(2*i+1) for i in range(TERMS)),Q(0))
    upper=lower+2*z**(2*TERMS+1)/(1-z*z)
    scale=1<<PREC
    return z,Q((lower*scale).__floor__(),scale),Q((upper*scale).__ceil__(),scale)

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--output',type=Path,default=ROOT/'LcmSix/LogCertificates.lean');ap.add_argument('--unit-limit',type=int);ap.add_argument('--write',action='store_true');args=ap.parse_args()
    if not __debug__: raise RuntimeError('Verification requires assertions enabled')
    raw=(ROOT/'cas/height-bounds/height_intervals.json').read_bytes(); heights=json.loads(raw)
    constants=json.loads((ROOT/'cas/height-bounds/duplication_bounds.json').read_text())
    units={Q(2):0}; records=[]
    for c,h in zip(constants['curves'],heights['curves'],strict=True):
        branch='Branch'+'_'.join(map(str,c['pair']))
        inputs=[('C',c['upper_coefficient_C']),('D',c['lower_coefficient_D'])]
        inputs += [(r['label'].replace('P1+P2','S12').replace('P1+P3','S13').replace('P2+P3','S23'),max(abs(int(r['iterate_x_numerator_hex'],16)),int(r['iterate_x_denominator_hex'],16))) for r in h['height_records']]
        for label,N in inputs:
            e=N.bit_length()-1; sh=max(0,e-59); mant,rem=divmod(N,1<<sh); den=1<<(e-sh)
            slo=Q(mant,den);shi=Q(mant+(rem>0),den)
            for s in [slo,shi]:
                if s not in units:units[s]=len(units)
            _,l2,u2=bounds(Q(2));_,ll,_=bounds(slo);_,_,uh=bounds(shi)
            lo=Q(((e*l2+ll)*(1<<48)).__floor__(),1<<48);hi=Q(((e*u2+uh)*(1<<48)).__ceil__(),1<<48)
            records.append(dict(branch=branch,label=label,N=N,e=e,slo=slo,shi=shi,l2=l2,u2=u2,ll=ll,uh=uh,lo=lo,hi=hi))
    s='''/-
Copyright (c) 2026 MaxwellLaw. Released under the Apache 2.0 license.
-/
import LcmSix.LogBounds

/-!
# Kernel-checked logarithm enclosures for the saved height data
Generated by scripts/export_log_certificates.py. The generator is untrusted;
all real bounds follow from LogBounds and explicit kernel-checked rational
inequalities. The underlying exact input JSON is fixed in the exporter.
-/
set_option maxRecDepth 100000
set_option exponentiation.threshold 300000
set_option maxHeartbeats 0
namespace LcmSix.LogCertificates
open LogBounds
'''
    for unit,i in units.items():
        if args.unit_limit is not None and i>=args.unit_limit:break
        z,lo,hi=bounds(unit)
        s+=f'''\nprivate theorem unit_{i} : ({rat(lo)}:ℝ)≤Real.log ({rat(unit)}:ℝ) ∧
    Real.log ({rat(unit)}:ℝ)≤({rat(hi)}:ℝ) := by
  simpa only [Rat.cast_div,Rat.cast_ofNat,Rat.cast_zero,Rat.cast_one] using
    (mantissa_log_bounds {TERMS} {rat(unit)} {rat(z)} {rat(lo)} {rat(hi)}
    (by norm_num) (by norm_num) (by norm_num)
    (by norm_num [lower, Finset.sum_range_succ])
    (by norm_num [upper, lower, Finset.sum_range_succ]))
'''
    if args.unit_limit is None:
        for r in records:
            name=r['branch']+'_'+r['label'];N=r['N']
            s+=f'''\ndef {name}_size : ℕ := {hex(N)}
theorem {name}_log : (({rat(r['lo'])}:ℚ):ℝ)≤Real.log ({name}_size:ℝ) ∧
    Real.log ({name}_size:ℝ)≤(({rat(r['hi'])}:ℚ):ℝ) := by
  apply integer_log_bounds {name}_size {r['e']} {rat(r['slo'])} {rat(r['shi'])}
    {rat(r['l2'])} {rat(r['u2'])} {rat(r['ll'])} {rat(r['uh'])}
    {rat(r['lo'])} {rat(r['hi'])}
  · decide
  · norm_num
  · exact scaled_lower {name}_size {r['e']} {r['slo'].numerator} {r['slo'].denominator} (by decide) (by decide)
  · exact scaled_upper {name}_size {r['e']} {r['shi'].numerator} {r['shi'].denominator} (by decide) (by decide)
  · simpa only [Rat.cast_div,Rat.cast_ofNat,Rat.cast_zero,Rat.cast_one] using unit_0
  · simpa only [Rat.cast_div,Rat.cast_ofNat,Rat.cast_zero,Rat.cast_one] using unit_{units[r['slo']]}.1
  · simpa only [Rat.cast_div,Rat.cast_ofNat,Rat.cast_zero,Rat.cast_one] using unit_{units[r['shi']]}.2
  · norm_num
  · norm_num
'''
    s+='\nend LcmSix.LogCertificates\n'
    if args.write or args.unit_limit is not None:
        args.output.write_text(s)
    else:
        assert args.output.read_text()==s, 'logarithm source differs from fixed exact data'
    print(json.dumps({'unit_count':len(units),'integer_log_count':len(records),'source_sha256':hashlib.sha256(raw).hexdigest(),'output_bytes':len(s.encode()),'unit_limit':args.unit_limit}))
if __name__=='__main__': main()
